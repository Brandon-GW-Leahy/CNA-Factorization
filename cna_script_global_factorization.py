def minimum_cost_spanning_tree(G):
    """
    Given a weighted directed graph G with a unique minimal element,
    return a minimum-cost spanning arborescence T.

    The unique vertex with indegree 0 is taken to be the root.
    """

    # Find the unique minimal element/root
    roots = [
        v for v in G.nodes()
        if G.in_degree(v) == 0
    ]

    if len(roots) != 1:
        raise ValueError(
            "G must have exactly one vertex with indegree 0."
        )

    root = roots[0]

    # Verify that every vertex is reachable from the root
    reachable = nx.descendants(G, root) | {root}

    if len(reachable) != G.number_of_nodes():
        raise ValueError(
            "Not every vertex of G is reachable from the root."
        )

    # Compute a minimum-cost spanning arborescence
    T = nx.minimum_spanning_arborescence(
        G,
        attr="weight"
    )

    return T

