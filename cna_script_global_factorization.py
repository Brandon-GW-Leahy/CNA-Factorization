"""Recompute problematic entries."""

def minimum_unused_interval_flow(x, U):
    """
    Re-decompose a nonnegative integer vector x using only mutations
    that are not already present in U.

    Parameters
    ----------
    x : array-like
        Target vector to decompose as a sum of consecutive-1 vectors.

    U : iterable of tuple[int, int]
        Mutations that have already been used in the phylogeny.
        Each mutation is stored as a 1-based inclusive interval
        (start, end).

    Returns
    -------
    (cost, flow, mutations)

    where

        cost:
            minimum number of selected interval edges

        flow:
            sparse dictionary of selected breakpoint edges

        mutations:
            selected 1-based inclusive intervals

    Returns None if no feasible decomposition exists.
    """

    x = np.asarray(x, dtype=int)

    if x.ndim != 1:
        raise ValueError("x must be a one-dimensional vector.")

    if np.any(x < 0):
        return None

    k = len(x)
    d = discrete_derivative(x)

    # Normalize U so membership tests are reliable.
    U = {tuple(mutation) for mutation in U}

    H = nx.DiGraph()

    # NetworkX convention is
    #
    #     inflow - outflow = demand,
    #
    # whereas partial(x) records outflow - inflow.
    for i in range(1, k + 2):
        H.add_node(
            i,
            demand=int(-d[i - 1])
        )

    # Breakpoint edge i -> j corresponds to interval [i, j-1].
    # Every already-used mutation receives capacity 0, i.e. bounds [0,0].
    # Every unused mutation receives capacity 1, i.e. bounds [0,1].
    for i in range(1, k + 1):
        for j in range(i + 1, k + 2):

            mutation = (i, j - 1)

            H.add_edge(
                i,
                j,
                capacity=0 if mutation in U else 1,
                weight=1
            )

    try:
        flow = nx.min_cost_flow(H)

    except nx.NetworkXUnfeasible:
        return None

    cost = nx.cost_of_flow(H, flow)

    used_flow = {}
    mutations = []

    for i, j in H.edges():

        f = flow[i][j]

        if f > 0:
            used_flow[(i, j)] = f
            mutations.append((i, j - 1))

    return cost, used_flow, mutations


def recompute_problematic_entries(local_info, problems, U):
    """
    Recompute the mutations removed by canonicalize_greedy for one
    local binary matrix.

    All problematic entries belonging to the same taxon are repaired
    together.  Thus, if taxon C_a has problematic mutations alpha and
    beta, the target vector is

        alpha + beta,

    and this function finds a minimum-size decomposition

        alpha + beta = alpha' + beta' + ...

    using only mutations not already in U.

    Parameters
    ----------
    local_info : dict
        One entry of the dictionary returned by
        build_local_binary_matrices(...).  In particular it contains

            local_info["taxa"]
            local_info["mutations"]
            local_info["mutation_vectors"]

    problems : list[tuple[int, int]]
        Output of canonicalize_greedy(local_info["matrix"]).
        Each pair is (local_row_index, local_column_index), using the
        original local matrix indices.

    U : iterable of tuple[int, int]
        Mutations already used in the phylogeny.

    Returns
    -------
    repairs : dict
        Indexed by the actual taxon index in T.  For each repaired taxon:

            repairs[taxon] = {
                "local_row": r,
                "old_mutations": [...],
                "target": np.ndarray,
                "replacement_cost": cost,
                "flow": {...},
                "new_mutations": [...]
            }

    updated_U : set
        U together with all newly selected replacement mutations.

    Returns None if some problematic taxon has no feasible repair.
    """

    taxa = local_info["taxa"]
    mutations = local_info["mutations"]
    mutation_vectors = local_info["mutation_vectors"]

    # Work with a copy so the caller's U is not modified unexpectedly.
    updated_U = {tuple(mutation) for mutation in U}

    # Group all problematic mutation columns by original local row.
    problems_by_row = {}

    for r, c in problems:

        if not (0 <= r < len(taxa)):
            raise IndexError(f"Problematic row index {r} is out of range.")

        if not (0 <= c < len(mutations)):
            raise IndexError(f"Problematic column index {c} is out of range.")

        problems_by_row.setdefault(r, []).append(c)

    repairs = {}

    # Deterministic order.  Because new mutations are added to updated_U,
    # later repairs cannot reuse a mutation introduced by an earlier repair.
    for r in sorted(problems_by_row):

        problematic_columns = problems_by_row[r]

        old_mutations = [
            tuple(mutations[c])
            for c in problematic_columns
        ]

        # This is alpha + beta + ... in the motivating example.
        target = np.sum(
            [
                np.asarray(mutation_vectors[c], dtype=int)
                for c in problematic_columns
            ],
            axis=0
        )

        result = minimum_unused_interval_flow(
            target,
            updated_U
        )

        if result is None:
            return None

        cost, flow, new_mutations = result

        taxon = taxa[r]

        repairs[taxon] = {
            "local_row": r,
            "old_mutations": old_mutations,
            "target": target,
            "replacement_cost": cost,
            "flow": flow,
            "new_mutations": new_mutations
        }

        # The replacement mutations are now used in the phylogeny.
        updated_U.update(new_mutations)

    return repairs, updated_U



