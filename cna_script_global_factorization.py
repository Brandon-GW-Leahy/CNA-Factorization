def generate_consecutive_ones(m, k, seed=None):
    if k < 1:
        raise ValueError("k must be at least 1.")

    # All intervals [i, j] with 1 <= i <= j <= k
    intervals = [
        (i, j)
        for i in range(1, k + 1)
        for j in range(i, k + 1)
    ]

    if m > len(intervals):
        raise ValueError(
            f"Cannot sample {m} distinct intervals. "
            f"There are only {len(intervals)} intervals in [1, {k}]."
        )

    if seed is not None:
        random.seed(seed)

    # Sample m distinct intervals without replacement
    sampled_intervals = random.sample(intervals, m)

    # Construct the m x k matrix
    B = np.zeros((m, k), dtype=int)

    for row, (i, j) in enumerate(sampled_intervals):
        # Convert from 1-based interval notation to Python indexing
        B[row, i - 1:j] = 1

    return B

