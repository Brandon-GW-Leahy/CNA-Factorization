import numpy as np
import networkx as nx


def discrete_derivative(x):
    """
    For x = (x1, ..., xk), compute

        partial(x) =
        (x1, x2-x1, ..., xk-x_{k-1}, -xk)

    This has length k+1.
    """

    x = np.asarray(x, dtype=int)

    return np.concatenate((
        [x[0]],
        np.diff(x),
        [-x[-1]]
    ))


def minimum_allowed_interval_flow(x, source, mutation_owner):
    """
    Compute a minimum-cost circulation for the difference vector x,
    subject to the mutations that have already been assigned.

    Parameters
    ----------
    x : array
        Difference C_b - C_a.

    source : int
        The source taxon C_a.

    mutation_owner : dict
        Maps an interval (i,j) to the source taxon that owns it.

        If mutation_owner[(i,j)] = a, then interval (i,j)
        may only be used by edges leaving C_a.

    Returns
    -------
    (cost, flow, mutations)

    where

        cost:
            minimum flow cost

        flow:
            sparse dictionary of used breakpoint edges

        mutations:
            list of consecutive-1 intervals

    Returns None if no feasible circulation exists.
    """

    x = np.asarray(x, dtype=int)

    if np.any(x < 0):
        return None

    k = len(x)

    d = discrete_derivative(x)

    H = nx.DiGraph()

    # ---------------------------------------------
    # Add breakpoint vertices 1,...,k+1
    # ---------------------------------------------

    for i in range(1, k + 2):

        # NetworkX convention:
        #
        #     inflow - outflow = demand
        #
        # so demand = -partial(x)
        H.add_node(
            i,
            demand=int(-d[i - 1])
        )

    # ---------------------------------------------
    # Add allowable interval edges
    # ---------------------------------------------

    for i in range(1, k + 1):

        for j in range(i + 1, k + 2):

            # Breakpoint edge i -> j corresponds
            # to the mutation/interval [i, j-1].
            interval = (i, j - 1)

            owner = mutation_owner.get(interval)

            # The interval may be used if:
            #
            # 1. nobody has used it yet, or
            # 2. it was previously used by an edge
            #    leaving this same source taxon.
            if owner is None or owner == source:

                H.add_edge(
                    i,
                    j,
                    capacity=1,
                    weight=1
                )

    # ---------------------------------------------
    # Find minimum-cost feasible circulation
    # ---------------------------------------------

    try:
        flow = nx.min_cost_flow(H)

    except nx.NetworkXUnfeasible:
        return None

    cost = nx.cost_of_flow(H, flow)

    # ---------------------------------------------
    # Extract only the nonzero flow edges
    # ---------------------------------------------

    used_flow = {}
    mutations = []

    for i, j in H.edges():

        f = flow[i][j]

        if f > 0:

            used_flow[(i, j)] = f

            # i -> j corresponds to interval [i,j-1]
            mutations.append((i, j - 1))

    return cost, used_flow, mutations


def compute_mutation_labels(T, C):
    """
    Compute mutation labels for every edge of the tree T.

    Edges are processed in increasing order of their original
    edge costs.

    If interval alpha is used on an edge leaving C_a, alpha
    becomes unavailable to every edge whose source is not C_a.

    Returns
    -------
    A copy of T whose edges additionally store:

        mutation_cost
        flow
        mutations

    Returns None if the algorithm encounters an edge for which
    no feasible circulation exists.
    """

    C = np.asarray(C, dtype=int)

    # Work on a copy so that the original tree is unchanged.
    labeled_T = T.copy()

    if labeled_T.number_of_edges() == 0:
        return labeled_T

    # --------------------------------------------------
    # mutation_owner[alpha] = a means mutation alpha
    # belongs to source taxon C_a.
    # --------------------------------------------------

    mutation_owner = {}

    # --------------------------------------------------
    # Find maximum edge cost m
    # --------------------------------------------------

    m = max(
        int(data["weight"])
        for _, _, data in labeled_T.edges(data=True)
    )

    # --------------------------------------------------
    # Process E_0, E_1, ..., E_m
    # --------------------------------------------------

    for ell in range(m + 1):

        E_ell = [
            (a, b)
            for a, b, data in labeled_T.edges(data=True)
            if int(data["weight"]) == ell
        ]

        # --------------------------------------------------
        # While E_ell is nonempty
        # --------------------------------------------------

        while E_ell:

            # Choose an edge C_a -> C_b.
            a, b = E_ell.pop(0)

            difference = C[b] - C[a]

            # Compute minimum-cost circulation under the
            # currently available mutations.
            result = minimum_allowed_interval_flow(
                difference,
                a,
                mutation_owner
            )

            # If no circulation exists, return FAIL.
            if result is None:
                return None

            cost, flow, mutations = result

            # --------------------------------------------------
            # Save f_e / mutation decomposition on edge C_a -> C_b
            # --------------------------------------------------

            labeled_T[a][b]["mutation_cost"] = cost
            labeled_T[a][b]["flow"] = flow
            labeled_T[a][b]["mutations"] = mutations

            # --------------------------------------------------
            # Every mutation used here is now owned by C_a.
            #
            # Consequently it will be unavailable in all future
            # breakpoint graphs corresponding to edges whose
            # source is not C_a.
            # --------------------------------------------------

            for alpha in mutations:

                if alpha not in mutation_owner:
                    mutation_owner[alpha] = a

                elif mutation_owner[alpha] != a:
                    # This should never occur because such an
                    # interval would not have been added to H.
                    raise RuntimeError(
                        f"Mutation {alpha} is already owned "
                        f"by another source."
                    )

    # Optional: save the ownership information with the tree.
    labeled_T.graph["mutation_owner"] = mutation_owner

    return labeled_T

"""For each node $C_a \in T$, we compute the associated binary matrix $A_a$ consisting of all cover relations leaving $C_a$ with $C_a$ the root."""

import numpy as np


def build_local_binary_matrices(labeled_T, C):
    """
    For every node C_a in labeled_T with at least one outgoing edge,
    construct the binary matrix A_a.

    Rows:
        C_a itself, followed by its immediate children.

    Columns:
        Distinct mutations/intervals appearing on edges leaving C_a.

    Entry:
        A_a[i,j] = 1 if the mutation corresponding to column j
        appears on the edge from C_a to the taxon corresponding
        to row i.

    Returns
    -------
    local_matrices : dict

        local_matrices[a] = {
            "matrix": A_a,
            "taxa": [...],
            "mutations": [...],
            "mutation_vectors": [...]
        }
    """

    C = np.asarray(C, dtype=int)
    k = C.shape[1]

    local_matrices = {}

    for a in labeled_T.nodes():

        children = list(labeled_T.successors(a))

        # Ignore leaves.
        if len(children) == 0:
            continue

        # --------------------------------------------------
        # Collect all distinct mutations on edges leaving C_a
        # --------------------------------------------------

        mutation_set = set()

        for b in children:

            edge_data = labeled_T[a][b]

            if "mutations" not in edge_data:
                raise ValueError(
                    f"Edge C_{a + 1} -> C_{b + 1} "
                    "does not have mutation labels."
                )

            for mutation in edge_data["mutations"]:
                mutation_set.add(tuple(mutation))

        # Give columns a deterministic ordering.
        mutations = sorted(mutation_set)

        # --------------------------------------------------
        # Rows are:
        #
        #     C_a, followed by all children of C_a.
        # --------------------------------------------------

        taxa = [a] + children

        # Map mutation -> column
        mutation_to_col = {
            mutation: j
            for j, mutation in enumerate(mutations)
        }

        # Construct binary matrix.
        A_a = np.zeros(
            (len(taxa), len(mutations)),
            dtype=int
        )

        # Row 0 corresponds to C_a, so it remains all zeros.

        # --------------------------------------------------
        # Fill rows corresponding to children
        # --------------------------------------------------

        for row_index, b in enumerate(children, start=1):

            for mutation in labeled_T[a][b]["mutations"]:

                mutation = tuple(mutation)

                col_index = mutation_to_col[mutation]

                A_a[row_index, col_index] = 1

        # --------------------------------------------------
        # Also construct actual binary interval vectors
        # corresponding to the mutation labels.
        #
        # For example:
        #
        #     (3,4) -> [0,0,1,1,0,0]
        # --------------------------------------------------

        mutation_vectors = []

        for start, end in mutations:

            v = np.zeros(k, dtype=int)

            # start/end use 1-based interval notation.
            v[start - 1:end] = 1

            mutation_vectors.append(v)

        local_matrices[a] = {
            "matrix": A_a,
            "taxa": taxa,
            "mutations": mutations,
            "mutation_vectors": mutation_vectors
        }

    return local_matrices

"""Greedy heuristic for the minimal changes to produce a perfect phylogeny."""

import numpy as np


def canonicalize_greedy(A):
    """
    Greedily transform a binary matrix A into a nearby
    perfect-phylogeny canonical form.

    The algorithm:
      1. Chooses the column with largest support first.
      2. Rearranges taxa so that its support is the first piece.
      3. Repeatedly chooses a remaining mutation c and current piece P
         maximizing |supp(c) ∩ P|.
      4. Any 1 of c outside P is declared problematic and changed to 0.
      5. P is split into the taxa having c=1 and the taxa having c=0.

    Returns
    -------
    A_prime : numpy.ndarray
        The reordered and corrected binary matrix.

    row_order : list[int]
        Original row indices in their new order.

    column_order : list[int]
        Original column indices in their new order.

    problems : list[tuple[int, int]]
        Pairs (taxon, mutation), using original zero-based indices,
        corresponding to entries changed from 1 to 0.
    """

    A = np.asarray(A, dtype=int)

    if A.ndim != 2:
        raise ValueError("A must be a 2-dimensional matrix.")

    if not np.all((A == 0) | (A == 1)):
        raise ValueError("A must be binary.")

    n, m = A.shape

    remaining_columns = list(range(m))
    column_order = []
    corrected_columns = {}
    problems = []

    # ------------------------------------------------------------
    # Step 1: choose the column with largest support
    # ------------------------------------------------------------

    first_column = max(
        remaining_columns,
        key=lambda c: (int(A[:, c].sum()), -c)
    )

    column_order.append(first_column)
    remaining_columns.remove(first_column)

    # The first selected mutation is kept unchanged.
    corrected_columns[first_column] = A[:, first_column].copy()

    # Rearrange taxa so its support comes first.
    ones = [
        r for r in range(n)
        if A[r, first_column] == 1
    ]

    zeros = [
        r for r in range(n)
        if A[r, first_column] == 0
    ]

    # Current ordered pieces of A'.
    pieces = []

    if ones:
        pieces.append(ones)

    if zeros:
        pieces.append(zeros)

    # ------------------------------------------------------------
    # Add the remaining mutations one at a time
    # ------------------------------------------------------------

    while remaining_columns:

        best_score = -1
        best_piece_index = None
        best_column = None

        # Choose c and piece A'_i maximizing
        #
        #       |supp(c) ∩ A'_i|.
        #
        # Ties:
        #   1. earliest current piece
        #   2. leftmost original mutation
        for piece_index, piece in enumerate(pieces):

            for c in remaining_columns:

                score = sum(A[r, c] for r in piece)

                if score > best_score:
                    best_score = score
                    best_piece_index = piece_index
                    best_column = c

                elif score == best_score:

                    if piece_index < best_piece_index:
                        best_piece_index = piece_index
                        best_column = c

                    elif (
                        piece_index == best_piece_index
                        and c < best_column
                    ):
                        best_column = c

        piece_index = best_piece_index
        c = best_column

        piece = pieces[piece_index]
        piece_set = set(piece)

        support = {
            r for r in range(n)
            if A[r, c] == 1
        }

        # --------------------------------------------------------
        # Keep only the support lying inside the chosen piece
        # --------------------------------------------------------

        ones_inside = [
            r for r in piece
            if r in support
        ]

        zeros_inside = [
            r for r in piece
            if r not in support
        ]

        # Any 1 outside the selected piece is problematic.
        problematic_rows = support - piece_set

        for r in sorted(problematic_rows):
            problems.append((r, c))

        # Corrected version of this column.
        corrected_column = np.zeros(n, dtype=int)

        for r in ones_inside:
            corrected_column[r] = 1

        corrected_columns[c] = corrected_column

        # --------------------------------------------------------
        # Split the chosen piece
        # --------------------------------------------------------

        new_pieces = []

        if ones_inside:
            new_pieces.append(ones_inside)

        if zeros_inside:
            new_pieces.append(zeros_inside)

        pieces = (
            pieces[:piece_index]
            + new_pieces
            + pieces[piece_index + 1:]
        )

        column_order.append(c)
        remaining_columns.remove(c)

    # ------------------------------------------------------------
    # Build final A'
    # ------------------------------------------------------------

    row_order = [
        r
        for piece in pieces
        for r in piece
    ]

    A_prime = np.column_stack([
        corrected_columns[c]
        for c in column_order
    ])

    A_prime = A_prime[row_order, :]

    return A_prime, row_order, column_order, problems


