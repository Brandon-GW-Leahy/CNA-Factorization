def apply_greedy_repairs(labeled_T, C):
    """
    Run canonicalize_greedy on every local binary matrix A_a and repair
    every problematic entry by re-decomposing its removed mutation sum
    using previously unused mutations.

    Returns
    -------
    repaired_T : networkx.DiGraph
        Copy of labeled_T with repaired mutation labels on its edges.

    local_results : dict
        Diagnostic information for each local matrix.

    U : set
        Final set of all mutations that are unavailable/used.

    Returns None if any local repair is infeasible.
    """

    repaired_T = labeled_T.copy()

    # Build the local matrices from the current edge labels.
    local_matrices = build_local_binary_matrices(
        repaired_T,
        C
    )

    # U initially contains every mutation already used anywhere in the
    # current phylogeny.  Hence every replacement mutation must be new.
    U = {
        tuple(mutation)
        for _, _, data in repaired_T.edges(data=True)
        for mutation in data.get("mutations", [])
    }

    local_results = {}

    for a, info in local_matrices.items():

        A_a = info["matrix"]

        # ----------------------------------------------------------
        # 1. Greedily canonicalize the local matrix A_a.
        # ----------------------------------------------------------
        A_prime, row_order, column_order, problems = canonicalize_greedy(
            A_a
        )

        # ----------------------------------------------------------
        # 2. Recompute the problematic entries using unused
        #    consecutive-1 mutations.
        # ----------------------------------------------------------
        result = recompute_problematic_entries(
            info,
            problems,
            U
        )

        if result is None:
            return None

        repairs, U = result

        # ----------------------------------------------------------
        # Update the mutation labels on the affected tree edges.
        #
        # If taxon C_b lost alpha,beta,... in the greedy correction,
        # replace those labels on edge C_a -> C_b by the newly found
        # alpha',beta',....  Their interval vectors have exactly the
        # same sum, so C_b - C_a is unchanged.
        # ----------------------------------------------------------
        for b, repair in repairs.items():

            if not repaired_T.has_edge(a, b):
                raise RuntimeError(
                    f"Local repair refers to C_{b + 1}, but "
                    f"C_{a + 1} -> C_{b + 1} is not an edge of T."
                )

            edge_data = repaired_T[a][b]

            old_problematic = {
                tuple(mutation)
                for mutation in repair["old_mutations"]
            }

            old_edge_mutations = [
                tuple(mutation)
                for mutation in edge_data["mutations"]
            ]

            kept_mutations = [
                mutation
                for mutation in old_edge_mutations
                if mutation not in old_problematic
            ]

            new_mutations = [
                tuple(mutation)
                for mutation in repair["new_mutations"]
            ]

            updated_mutations = kept_mutations + new_mutations

            edge_data["mutations"] = updated_mutations
            edge_data["mutation_cost"] = len(updated_mutations)

            # Each selected interval carries one unit of flow.
            edge_data["flow"] = {
                (start, end + 1): 1
                for start, end in updated_mutations
            }

        local_results[a] = {
            "A": A_a,
            "A_prime": A_prime,
            "row_order": row_order,
            "column_order": column_order,
            "problems": problems,
            "repairs": repairs
        }

    repaired_T.graph["used_mutations"] = set(U)

    return repaired_T, local_results, U



def build_global_factorization(repaired_T, C):
    """
    Construct the global factorization C = A B from the repaired tree.

    Each distinct mutation/interval is one column of A and the
    corresponding consecutive-1 interval vector is one row of B.

    A[v,j] = 1 exactly when mutation j occurs on the unique path from
    the root of repaired_T to taxon C_v.
    """

    C = np.asarray(C, dtype=int)
    n, k = C.shape

    roots = [
        v for v in repaired_T.nodes()
        if repaired_T.in_degree(v) == 0
    ]

    if len(roots) != 1:
        raise ValueError("The repaired tree must have exactly one root.")

    root = roots[0]

    # The current formulation represents C directly as A @ B, so the
    # root taxon must be the all-zero copy-number vector.
    if not np.all(C[root] == 0):
        return None

    # One global column/row per distinct mutation.
    mutation_order = sorted({
        tuple(mutation)
        for _, _, data in repaired_T.edges(data=True)
        for mutation in data.get("mutations", [])
    })

    mutation_to_col = {
        mutation: j
        for j, mutation in enumerate(mutation_order)
    }

    q = len(mutation_order)

    A_global = np.zeros((n, q), dtype=int)
    B_global = np.zeros((q, k), dtype=int)

    # Construct B directly from the interval labels.
    for j, (start, end) in enumerate(mutation_order):
        B_global[j, start - 1:end] = 1

    # Propagate all mutations along root-to-taxon paths.
    # Because repaired_T is an arborescence, each non-root vertex has
    # a unique parent.
    for v in nx.topological_sort(repaired_T):

        if v == root:
            continue

        predecessors = list(repaired_T.predecessors(v))

        if len(predecessors) != 1:
            raise ValueError(
                "Every non-root vertex must have exactly one parent."
            )

        parent = predecessors[0]

        # Inherit all mutations present in the parent taxon.
        A_global[v] = A_global[parent]

        # Add the mutations separating parent and child.
        for mutation in repaired_T[parent][v].get("mutations", []):
            mutation = tuple(mutation)
            A_global[v, mutation_to_col[mutation]] = 1

    return A_global, B_global, mutation_order



def is_perfect_phylogeny_matrix(A):
    """
    Check the rooted binary perfect-phylogeny condition: for every pair
    of columns, their supports must be nested or disjoint.
    """

    A = np.asarray(A, dtype=int)

    if A.ndim != 2:
        return False

    if not np.all((A == 0) | (A == 1)):
        return False

    m = A.shape[1]

    supports = [
        set(np.flatnonzero(A[:, j]))
        for j in range(m)
    ]

    for i in range(m):
        for j in range(i + 1, m):

            S = supports[i]
            T = supports[j]

            if S.isdisjoint(T):
                continue

            if S.issubset(T) or T.issubset(S):
                continue

            return False

    return True



def is_consecutive_ones_matrix(B):
    """Return True iff every row of B is a binary consecutive-1 vector."""

    B = np.asarray(B, dtype=int)

    if B.ndim != 2:
        return False

    if not np.all((B == 0) | (B == 1)):
        return False

    for row in B:

        ones = np.flatnonzero(row)

        if len(ones) == 0:
            continue

        if ones[-1] - ones[0] + 1 != len(ones):
            return False

    return True


