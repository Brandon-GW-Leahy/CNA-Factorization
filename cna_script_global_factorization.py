def discrete_derivative(x):
    """
    For x = (x1, ..., xk), return

        partial(x) = (x1,
                      x2-x1,
                      ...,
                      xk-x_{k-1},
                      -xk)

    This has length k+1.
    """
    x = np.asarray(x, dtype=int)

    return np.concatenate((
        [x[0]],
        np.diff(x),
        [-x[-1]]
    ))


def minimum_interval_cost(x):
    """
    Given a nonnegative integer vector x, construct the breakpoint
    graph H_{partial(x)} and compute the minimum-cost feasible flow.

    Returns:
        minimum cost

    or None if no feasible flow exists.
    """

    x = np.asarray(x, dtype=int)
    k = len(x)

    if np.any(x < 0):
        return None

    d = discrete_derivative(x)

    H = nx.DiGraph()

    # NetworkX uses:
    #
    #     inflow - outflow = demand
    #
    # while partial(x) represents:
    #
    #     outflow - inflow.
    #
    # Therefore demand = -partial(x).
    for i in range(1, k + 2):
        H.add_node(
            i,
            demand=int(-d[i - 1])
        )

    # Add every edge i -> j for i < j.
    # Each edge represents one consecutive-1 interval.
    for i in range(1, k + 1):
        for j in range(i + 1, k + 2):
            H.add_edge(
                i,
                j,
                capacity=1,
                weight=1
            )

    try:
        flow = nx.min_cost_flow(H)
    except nx.NetworkXUnfeasible:
        return None

    return nx.cost_of_flow(H, flow)


def build_graph(C):
    """
    Given an n x k observed copy-number matrix C,
    construct the directed weighted graph G.

    An edge

        C_b -> C_a

    exists when C_a - C_b is nonnegative and has a feasible
    unit-capacity consecutive-1 decomposition.

    Only the minimum cost is stored on the edge.
    """

    C = np.asarray(C, dtype=int)

    if C.ndim != 2:
        raise ValueError("C must be a 2-dimensional matrix.")

    n, k = C.shape

    G = nx.DiGraph()

    # Use row indices as vertices.
    for a in range(n):
        G.add_node(a)

    # Consider every ordered pair of rows.
    for a in range(n):
        for b in range(n):

            if a == b:
                continue

            difference = C[a] - C[b]

            # Toss differences with negative coordinates.
            if np.any(difference < 0):
                continue

            cost = minimum_interval_cost(difference)

            # Add C_b -> C_a if a feasible decomposition exists.
            if cost is not None:
                G.add_edge(
                    b,
                    a,
                    weight=cost
                )

    return G


