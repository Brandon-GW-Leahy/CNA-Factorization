    # A_1
    A = np.array([
        [0],
        [1]
    ], dtype=int)

    # Inductively construct A with m columns.
    for i in range(1, m):

        # Select an existing row at random
        r = random.randrange(A.shape[0])

        # Duplicate row r and insert the copy immediately below it
        A = np.insert(A, r + 1, A[r], axis=0)

        # Add a new column of zeros
        new_column = np.zeros((A.shape[0], 1), dtype=int)
        A = np.hstack((A, new_column))

        # Assign 1 to the new column in the copied row
        A[r + 1, -1] = 1

    # Delete m+1-n randomly selected rows
    rows_to_delete = (m + 1) - n

    if rows_to_delete > 0:

        # Find the all-zero row
        zero_row_index = np.where(
            np.all(A == 0, axis=1)
        )[0][0]

        # Every row except the all-zero row may be deleted
        eligible_indices = [
            i for i in range(A.shape[0])
            if i != zero_row_index
        ]

        delete_indices = random.sample(
            eligible_indices,
            rows_to_delete
        )

        A = np.delete(A, delete_indices, axis=0)

    return A

